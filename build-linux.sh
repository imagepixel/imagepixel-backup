#!/usr/bin/env bash
# Builds the application for Linux and packs it for the two families of systems:
#
#   artifacts/linux/imagepixel-backup_<version>_amd64.deb              Ubuntu and its relatives
#   artifacts/linux/imagepixel-backup-<version>-1-x86_64.pkg.tar.zst   CachyOS and other Arch systems
#
# Both hold the same files: the application with the .NET runtime and restic in
# /opt/imagepixel-backup, an entry for the menu, and the icon.
#
# Must run on Linux. Requirements: Git, Go, the .NET 10 SDK, dpkg-deb, bsdtar and zstd.
set -euo pipefail

root="$(cd "$(dirname "$0")" && pwd)"
project="$root/src/ImagepixelBackup.App/ImagepixelBackup.App.csproj"
version="$(sed -n 's:.*<Version>\(.*\)</Version>.*:\1:p' "$project" | head -n 1)"
if [ -z "$version" ]; then
    echo "No <Version> found in $project" >&2
    exit 1
fi

name="imagepixel-backup"
summary="Backs up folders and restores them, built on restic"
homepage="https://github.com/imagepixel/imagepixel-backup"
maintainer="Imagepixel <post@imagepixel.de>"

if [ ! -f "$root/bin/restic-linux-amd64" ]; then
    bash "$root/build-restic.sh"
fi

out="$root/artifacts/linux"
rm -rf "$out"
mkdir -p "$out"

publish="$root/artifacts/publish-linux-x64"
rm -rf "$publish"
echo "Publishing the application for linux-x64 ..."
dotnet publish "$project" --configuration Release --runtime linux-x64 --self-contained true \
    -p:DebugType=none -p:DebugSymbols=false --output "$publish" --nologo --verbosity quiet

# Lays out the files below a folder as they lie on the computer after the installation.
stage() {
    local tree="$1"
    install -d "$tree/opt/$name" "$tree/usr/bin" "$tree/usr/share/applications"
    cp -R "$publish/." "$tree/opt/$name/"
    ln -s "/opt/$name/ImagepixelBackup" "$tree/usr/bin/$name"
    cp "$root/installer/linux/$name.desktop" "$tree/usr/share/applications/$name.desktop"
    for size in 48 64 128 256 512; do
        install -d "$tree/usr/share/icons/hicolor/${size}x${size}/apps"
        cp "$root/installer/linux/icons/$size.png" "$tree/usr/share/icons/hicolor/${size}x${size}/apps/$name.png"
    done

    # the same rights wherever the files were built
    find "$tree" -type d -exec chmod 755 {} +
    find "$tree" -type f -exec chmod 644 {} +
    chmod 755 "$tree/opt/$name/ImagepixelBackup" "$tree/opt/$name/restic"
}

# --- Ubuntu ---------------------------------------------------------------------------
echo "Packing for Ubuntu ..."
deb="$out/deb"
stage "$deb"
install -d "$deb/usr/share/doc/$name" "$deb/DEBIAN"
install -m 644 "$root/LICENSE" "$deb/usr/share/doc/$name/copyright"
install -m 644 "$root/THIRD-PARTY-NOTICES.txt" "$deb/usr/share/doc/$name/THIRD-PARTY-NOTICES.txt"
install -m 644 "$root/NUTZUNGSHINWEISE.md" "$deb/usr/share/doc/$name/NUTZUNGSHINWEISE.md"

# The keyring is reached through secret-tool, the drive through FUSE, and the rest is
# what the user interface needs. The libraries for languages (ICU) carry their version
# in the name of their package, so they are only recommended: a system that calls
# them differently still installs the package, and every desktop has them anyway.
cat > "$deb/DEBIAN/control" << EOF
Package: $name
Version: $version
Section: utils
Priority: optional
Architecture: amd64
Maintainer: $maintainer
Installed-Size: $(du -sk --exclude=DEBIAN "$deb" | cut -f1)
Depends: libsecret-tools, fuse3, xdg-utils, libx11-6, libice6, libsm6, libfontconfig1
Recommends: libicu78 | libicu77 | libicu76 | libicu75 | libicu74 | libicu72 | libicu70
Homepage: $homepage
Description: $summary
 Imagepixel Backup keeps backing up simple: choose what to back up and where
 to, and it runs in the background from then on. The data is encrypted on
 this computer before it leaves it.
EOF
dpkg-deb --root-owner-group -Zxz --build "$deb" "$out/${name}_${version}_amd64.deb" > /dev/null
rm -rf "$deb"
echo "Done: $out/${name}_${version}_amd64.deb"

# --- CachyOS ---------------------------------------------------------------------------
echo "Packing for CachyOS ..."
pkg="$out/pkg"
stage "$pkg"
install -d "$pkg/usr/share/licenses/$name"
install -m 644 "$root/LICENSE" "$pkg/usr/share/licenses/$name/LICENSE"
install -m 644 "$root/THIRD-PARTY-NOTICES.txt" "$pkg/usr/share/licenses/$name/THIRD-PARTY-NOTICES.txt"
install -m 644 "$root/NUTZUNGSHINWEISE.md" "$pkg/usr/share/licenses/$name/NUTZUNGSHINWEISE.md"

cat > "$pkg/.PKGINFO" << EOF
# Generated by build-linux.sh
pkgname = $name
pkgbase = $name
xdata = pkgtype=pkg
pkgver = $version-1
pkgdesc = $summary
url = $homepage
builddate = $(date +%s)
packager = $maintainer
size = $(du -sb "$pkg" | cut -f1)
arch = x86_64
license = BSD-2-Clause
depend = libsecret
depend = fuse3
depend = xdg-utils
depend = libx11
depend = libice
depend = libsm
depend = fontconfig
depend = icu
depend = openssl
EOF

# a package of pacman is an archive of the files, their description and a list to check them against
(
    cd "$pkg"
    LANG=C bsdtar --uid 0 --gid 0 -czf .MTREE --format=mtree \
        --options='!all,use-set,type,uid,gid,mode,time,size,md5,sha256,link' .PKGINFO *
    LANG=C bsdtar --uid 0 --gid 0 --uname root --gname root -cf - .MTREE .PKGINFO * \
        | zstd -q -c -T0 -19 > "$out/$name-$version-1-x86_64.pkg.tar.zst"
)
rm -rf "$pkg"
echo "Done: $out/$name-$version-1-x86_64.pkg.tar.zst"
